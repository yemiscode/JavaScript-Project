// add a new item to the begging of an array and it can also return the new length it is like the opposite of the push array method
const fruits = ['mango', 'orange', 'banana', 'apple'];
const unshift = fruits.unshift('lemon');
console.log(fruits);
console.log(unshift);


// answer
// (5) ['lemon', 'mango', 'orange', 'banana', 'apple']
